"""Encode baked PNG frames (tools/bake.py output) into the responsive WebP sets + manifest + inline static fallbacks.
usage: encode_frames.py <bakeL_dir> <bakeP_dir> <ps.json> [staticL_dir staticP_dir]   (run from the project root)
The optional static dirs hold an off-centre render of the final pose (bake.py with SHIFT) used as the inline fallback poster."""
import sys, os, json, glob, io
import numpy as np
from PIL import Image
L, P, PSJ = sys.argv[1:4]
SL, SP = (sys.argv[4], sys.argv[5]) if len(sys.argv) > 5 else (L, P)
ps = json.load(open(PSJ)); n = len(ps)
OUT = 'assets/animation'
SETS = {'lg': (L, (1800, 900), OUT + '/'), 'md': (L, (1200, 600), OUT + '/md/'), 'pt': (P, (600, 1300), OUT + '/pt/')}
Q = 88
rng = np.random.default_rng(7)
def dither(im, s=0.9):
    a = np.asarray(im, np.float32) + rng.normal(0, s, (im.size[1], im.size[0], 1)).astype(np.float32)   # luma-only grain hides banding in the soft backdrop
    return Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8))
def enc(im, q=Q): b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6); return b.getvalue()
tot = {}
for sid, (src, size, d) in SETS.items():
    os.makedirs(d, exist_ok=True)
    for f in glob.glob(d + 'frame_*.webp'): os.remove(f)
    t = 0
    for i, p in enumerate(ps):
        im = Image.open(f'{src}/p_{p:.4f}.png').convert('RGB').resize(size, Image.LANCZOS)
        data = enc(dither(im)); open(f'{d}frame_{i:03d}.webp', 'wb').write(data); t += len(data)
    tot[sid] = t; print(sid, n, 'frames', round(t / 1024), 'KB total', round(t / n / 1024, 1), 'KB avg')
# inline static fallbacks (final attached presentation) + tiny sample of the backdrop colour
for sid, src, size, name in (('l', SL, (960, 480), 'static_l'), ('p', SP, (360, 780), 'static_p')):
    im = Image.open(f'{src}/p_{ps[-1]:.4f}.png').convert('RGB').resize(size, Image.LANCZOS)
    open(f'assets/animation/{name}.webp', 'wb').write(enc(dither(im), 80)); print(name, len(enc(im, 80)) // 1024, 'KB')
man = {'count': n, 'p': ps, 'sets': {'lg': {'w': 1800, 'h': 900, 'dir': 'assets/animation/'}, 'md': {'w': 1200, 'h': 600, 'dir': 'assets/animation/md/'}, 'pt': {'w': 600, 'h': 1300, 'dir': 'assets/animation/pt/'}}}
open('src/hero/manifest.generated.ts', 'w').write('// GENERATED by tools/encode_frames.py: progress (0..1) of each baked frame, and the responsive sets\nexport type SetId = \'lg\' | \'md\' | \'pt\';\nexport const MANIFEST = ' + json.dumps(man) + ' as { count: number; p: number[]; sets: Record<SetId, { w: number; h: number; dir: string }> };\n')
